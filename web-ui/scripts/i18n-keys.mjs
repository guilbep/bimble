// Writes src/i18n/keys.gen.ts: the union of the keys of every src/i18n/parts/*.ts, so t() checks its key at compile time
// while index.ts loads the parts with import.meta.glob (no hand-kept list). `--check`: exit 1 if the file is stale.
// Node strips the TypeScript types on import (Node >= 22.18); the parts must stay import-free data.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const dir = join(import.meta.dirname, "../src/i18n");
const keys = new Set();
for (const f of readdirSync(join(dir, "parts")).filter((f) => f.endsWith(".ts")).sort()) {
  const { fr } = await import(pathToFileURL(join(dir, "parts", f)).href);
  for (const k of Object.keys(fr)) keys.add(k);
}
const list = [...keys].sort();
const body = list.length ? list.map((k) => `\n  | ${JSON.stringify(k)}`).join("") : " never";
const out = `// Generated by scripts/i18n-keys.mjs from src/i18n/parts/*.ts. Do not edit: run \`npm run i18n-keys\`.\nexport type PartKey =${body};\n`;
const file = join(dir, "keys.gen.ts");
let old = "";
try { old = readFileSync(file, "utf8"); } catch { /* first run */ }
if (process.argv.includes("--check")) {
  if (old !== out) { console.error("src/i18n/keys.gen.ts is stale: run `npm run i18n-keys` and commit it"); process.exit(1); }
} else if (old !== out) writeFileSync(file, out);
console.log(`i18n-keys: ${list.length} part keys`);
