"""Generate crates/bimble-core/src/crs_table.rs: the coordinate systems Bimble offers (ADR 0045),
from the crs-definitions crate's EPSG data (CC0): Swiss LV95 and LV03, ETRS89 / UTM zones (Europe)
and the NAD83 State Plane zones of the US states, in metres and in feet.

Usage: python3 -I scripts/gen_crs_table.py [path/to/crs-definitions/src/defs.rs]
(default: the copy in ~/.cargo/registry, fetched by `cargo fetch` with crs-definitions 0.6.)
"""

import glob
import os
import re
import sys

STATES = """Alabama Alaska Arizona Arkansas California Colorado Connecticut Delaware Florida Georgia
Hawaii Idaho Illinois Indiana Iowa Kansas Kentucky Louisiana Maine Maryland Massachusetts Michigan
Minnesota Mississippi Missouri Montana Nebraska Nevada New_Hampshire New_Jersey New_Mexico New_York
North_Carolina North_Dakota Ohio Oklahoma Oregon Pennsylvania Rhode_Island South_Carolina
South_Dakota Tennessee Texas Utah Vermont Virginia Washington West_Virginia Wisconsin Wyoming
District_of_Columbia Puerto_Rico""".split()
STATES = [s.replace("_", " ") for s in STATES]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else glob.glob(os.path.expanduser(
        "~/.cargo/registry/src/*/crs-definitions-0.6.*/src/defs.rs"))[0]
    rows = []
    for line in open(src, encoding="utf-8"):
        if not line.startswith("EPSG_"):
            continue
        _, code, proj, wkt = line.split("|", 3)
        m = re.search(r'PROJCS\["([^"]+)"', wkt)
        if not m:
            continue
        code, name, proj = int(code), m.group(1), proj.strip('"')
        swiss = code in (2056, 21781)
        utm = re.fullmatch(r"ETRS89 / UTM zone \d+N", name)
        state = (name.startswith("NAD83 / ") and not re.search(r"HARN|NSRS|CSRS|2011|UTM|Albers", name)
                 and any(name[8:].startswith(s) for s in STATES))
        if swiss or utm or state:
            rows.append((code, name, proj))
    rows.sort()
    out = ["// Generated by scripts/gen_crs_table.py from crs-definitions (EPSG data, CC0). Do not edit.",
           "",
           "/// (EPSG code, name, PROJ.4 definition) of the systems Bimble offers.",
           f"pub const SYSTEMS: [(u16, &str, &str); {len(rows)}] = ["]
    for code, name, proj in rows:
        out.append(f"    ({code}, {name!r}, {proj!r}),".replace("'", '"'))
    out.append("];")
    path = os.path.join(os.path.dirname(__file__), "..", "crates", "bimble-core", "src", "crs_table.rs")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(rows)} systems → {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
