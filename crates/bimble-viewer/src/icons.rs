/// One piece of an icon on the 24 × 24 grid.
enum Part {
    /// An open polyline.
    Line(&'static [[f32; 2]]),
    /// A closed polygon, outlined.
    Poly(&'static [[f32; 2]]),
    /// A dashed polyline.
    Dashed(&'static [[f32; 2]]),
    /// A circle: centre, radius.
    Circle([f32; 2], f32),
    /// A filled polygon.
    Fill(&'static [[f32; 2]]),
}

