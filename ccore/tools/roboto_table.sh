#!/usr/bin/env bash
# Writes src/roboto_widths.inc from golden/drawing/roboto.txt (Rust's Roboto metrics, ticket D1):
# per face the code points, glyph ids and advances in font units (Roboto: 2048 per em, so an
# advance of 1/1000 em is units * 0.48828125, exact in f32). test/draw_test.c checks the table
# against roboto.txt. Usage: ccore/tools/roboto_table.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
awk '
function units(a) { u = a / 0.48828125; return int(u + (u < 0 ? -0.5 : 0.5)) }
$1 == "face" { f++; n = 0; next }
$1 == "missing" { miss[f] = units($2); next }
NF == 3 && $1 ~ /^[0-9a-f]+$/ { n++; cp[n] = $1; gid[f, n] = $2; adv[f, n] = units($3); N = n; next }
END {
    print "/* Generated by tools/roboto_table.sh from golden/drawing/roboto.txt: do not edit. */"
    printf "#define ROBOTO_N %d\n", N
    printf "static const uint16_t ROBOTO_MISSING[2] = {%d, %d};\n", miss[1], miss[2]
    printf "static const uint16_t ROBOTO_CP[ROBOTO_N] = {"
    for (i = 1; i <= N; i++) printf "%s0x%s", (i > 1 ? (i % 12 == 1 ? ",\n    " : ", ") : "\n    "), cp[i]
    print "};"
    for (k = 1; k <= 2; k++) {
        printf "static const uint16_t ROBOTO_GID_%d[ROBOTO_N] = {", k - 1
        for (i = 1; i <= N; i++) printf "%s%d", (i > 1 ? (i % 16 == 1 ? ",\n    " : ", ") : "\n    "), gid[k, i]
        print "};"
        printf "static const uint16_t ROBOTO_UNITS_%d[ROBOTO_N] = {", k - 1
        for (i = 1; i <= N; i++) printf "%s%d", (i > 1 ? (i % 16 == 1 ? ",\n    " : ", ") : "\n    "), adv[k, i]
        print "};"
    }
}' "$root/golden/drawing/roboto.txt" > "$root/src/roboto_widths.inc"
