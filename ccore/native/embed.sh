#!/usr/bin/env bash
# Writes a C file holding each input file as an array (ticket NUI1: the native app's data and fonts,
# ui/embed.h). POSIX od only (no xxd, no C23 #embed: tcc builds it).
#   native/embed.sh out.c file...
set -euo pipefail
out=$1
shift
tmp=$out.tmp.$$
{
    echo '/* Generated by ccore/native/embed.sh: do not edit. */'
    echo '#include "embed.h"'
    i=0
    for f in "$@"; do
        echo "static const unsigned char B$i[] = {"
        od -An -v -tu1 "$f" | sed -e 's/^ *//' -e 's/  */,/g' -e 's/$/,/' -e '/^,$/d'
        echo "0};"
        i=$((i + 1))
    done
    echo "const nui_blob NUI_BLOBS[] = {"
    i=0
    for f in "$@"; do
        printf '    {"%s", B%d, %d},\n' "$(basename "$f")" "$i" "$(wc -c < "$f")"
        i=$((i + 1))
    done
    echo "};"
    echo "const size_t NUI_NBLOBS = sizeof NUI_BLOBS / sizeof *NUI_BLOBS;"
    cat << 'EOF'
#include <string.h>
const nui_blob *nui_blob_get(const char *name) {
    for (size_t k = 0; k < NUI_NBLOBS; k++)
        if (!strcmp(NUI_BLOBS[k].name, name)) return &NUI_BLOBS[k];
    return NULL;
}
EOF
} > "$tmp"
mv "$tmp" "$out"
